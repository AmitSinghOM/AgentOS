"""Regenerate deploy/constraints.txt: every third-party distribution the image installs, pinned
to one version with the sha256 of every file PyPI serves for it (audit I-21 / E-20).

    python scripts/refresh_constraints.py            # rewrite deploy/constraints.in + .txt
    python scripts/refresh_constraints.py --check    # exit 1 if the committed files are stale

What is pinned: the dependencies of `dagentos[providerkit,observability]` and of the five
providers (read from their pyproject.toml files here, so the list cannot drift from the
floors), plus `pip` itself (the Dockerfile upgrades it). Our own distributions are NOT in the
file: the image installs them from the wheels the same run built, by path, with `--no-deps`.

Why uv and not pip-compile: pip-compile resolves for the machine it runs on, so a run on
macOS silently drops anything behind a `sys_platform == "linux"` marker and the amd64+arm64
image build fails later. `uv pip compile --universal` keeps the markers and emits one file
that is correct on every platform; `--python-version 3.12` matches the image's interpreter.
uv is a single binary (`pip install uv`, or the `UV` env var pointing at one).

When to run: before every release (docs/RELEASING.md § Reproducible image) and after any
Dependabot `pip` group merges, since those move the floors the resolution starts from.
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IN_FILE = ROOT / "deploy" / "constraints.in"
OUT_FILE = ROOT / "deploy" / "constraints.txt"
PYTHON_VERSION = "3.12"           # the Dockerfile's `FROM python:3.12-slim`
EXTRAS = ("providerkit", "observability")   # what the Dockerfile installs from the core wheel
OWN_DISTRIBUTIONS = {"dagentos"}            # installed by wheel path, never from an index


def direct_requirements() -> list[str]:
    core = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    reqs = list(core["dependencies"])
    for extra in EXTRAS:
        reqs += core["optional-dependencies"][extra]
    for p in sorted((ROOT / "providers").glob("*/pyproject.toml")):
        reqs += tomllib.loads(p.read_text())["project"]["dependencies"]
    third_party = []
    for r in reqs:
        name = r.split(";")[0].split("[")[0].split(">")[0].split("<")[0].split("=")[0].strip()
        if name.lower() in OWN_DISTRIBUTIONS:
            continue
        if r not in third_party:
            third_party.append(r)
    third_party.append("pip")
    return third_party


def render_in_file() -> str:
    extras = ",".join(EXTRAS)
    lines = [
        f"# Generated by scripts/refresh_constraints.py from pyproject.toml [{extras}] and",
        "# providers/*/pyproject.toml. Do not edit; rerun the script.",
        "# Compiled into constraints.txt (hash-pinned) for the Dockerfile.",
    ]
    return "\n".join(lines + direct_requirements()) + "\n"


def uv_binary() -> str:
    uv = os.environ.get("UV") or shutil.which("uv")
    if not uv:
        sys.exit("uv not found: `pip install uv` (or set UV=/path/to/uv) and rerun")
    return uv


def compile_(in_file: Path, out_file: Path) -> None:
    cmd = [
        uv_binary(), "pip", "compile",
        "--universal",
        "--python-version", PYTHON_VERSION,
        "--generate-hashes",
        "--no-strip-markers",
        "--custom-compile-command", "python scripts/refresh_constraints.py",
        "--output-file", str(out_file),
        str(in_file),
    ]
    subprocess.run(cmd, check=True, cwd=ROOT)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if deploy/constraints.{in,txt} would change")
    args = ap.parse_args()

    new_in = render_in_file()
    if args.check:
        tmp_in = OUT_FILE.with_suffix(".check.in")
        tmp_out = OUT_FILE.with_suffix(".check.txt")
        try:
            tmp_in.write_text(new_in)
            compile_(tmp_in, tmp_out)
            stale = (not IN_FILE.is_file() or IN_FILE.read_text() != new_in
                     or not OUT_FILE.is_file()
                     or _body(OUT_FILE.read_text()) != _body(tmp_out.read_text()))
        finally:
            tmp_in.unlink(missing_ok=True)
            tmp_out.unlink(missing_ok=True)
        if stale:
            print("deploy/constraints.txt is stale: run `python scripts/refresh_constraints.py`")
            return 1
        print("deploy/constraints.txt is current")
        return 0

    IN_FILE.write_text(new_in)
    compile_(IN_FILE, OUT_FILE)
    print(f"wrote {IN_FILE.relative_to(ROOT)} and {OUT_FILE.relative_to(ROOT)}")
    return 0


def _body(text: str) -> str:
    """The compiled file minus comments: the header and the `# via -r <path>` lines name the
    input file, which differs between the committed file and the --check scratch copy."""
    return "\n".join(ln for ln in text.splitlines() if not ln.lstrip().startswith("#"))


if __name__ == "__main__":
    sys.exit(main())
